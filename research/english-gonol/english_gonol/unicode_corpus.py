def _manifest_for(source_manifest, counts, rows_sha256):
    return {'schema': PROFILE, 'geometry': unicode.authority(), 'implementation': _implementation(),
            'admission': source_manifest['receipt_sha256'], 'unicode_release': inputs.UCD_RELEASE_SHA256,
            'geometry_rows_sha256': rows_sha256, 'counts': counts,
            'source_counts': source_manifest['counts'], 'placement_radius': [1, 1],
            'parent_bearings': 'caller-declared', 'source_definition_attachment': 'SPACE',
            'scope': 'native glyph and word geometry; ordered higher source relations retain exact admission'}


def _check_rows(source, source_manifest, blobs, native, db, *, write):
    counts = {}
    hasher = sha256()
    for (table, order, size), expected in zip(TABLES, _rows(source, source_manifest, blobs, native), strict=True):
        hasher.update(table.encode() + b'\n')
        stored = None if write else iter(db.execute(f'SELECT * FROM {table} ORDER BY {order}'))
        count = 0
        for row in expected:
            if stored is not None and next(stored, None) != row:
                raise ValueError(f'{table} replay mismatch at row {count}')
            if write:
                db.execute(f'INSERT INTO {table} VALUES({",".join("?" * size)})', row)
            hasher.update(canonical([x.hex() if isinstance(x, bytes) else x for x in row]) + b'\n')
            count += 1
        if stored is not None and next(stored, None) is not None:
            raise ValueError(f'extra {table} row after {count}')
        counts[table] = count
    return _manifest_for(source_manifest, counts, hasher.hexdigest())


@contextmanager
def _verified(directory, native):
    root = Path(directory)
    raw = inputs.bounded_bytes(root / 'manifest.json', 1_000_000, 'Unicode corpus manifest')
    blobs = inputs.unicode_blobs(root / 'ucd')
    with admission(root / 'admission') as (source, source_manifest), closing(open_readonly(root / 'geometry.db')) as db:
        db.execute('BEGIN')
        with closing(sqlite3.connect(':memory:')) as schema:
            schema.executescript(SQL)
            if _schema(db) != _schema(schema):
                raise ValueError('Unicode corpus schema mismatch')
        expected = _check_rows(source, source_manifest, blobs, native, db, write=False)
        if canonical(expected) + b'\n' != raw:
            raise ValueError('Unicode corpus manifest mismatch')
        yield source, source_manifest, db, expected


def build(source_dir, ucd, output, native_root):
    native = unicode._native(native_root)
    output = Path(output)
    if output.exists():
        raise FileExistsError(output)
    blobs = inputs.unicode_blobs(ucd)
    output.parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(prefix='.unicode-corpus-', dir=output.parent))
    try:
        with admission(source_dir) as (source, manifest):
            _copy_admission(source, manifest, stage / 'admission')
            (stage / 'ucd').mkdir()
            for name, raw in blobs.items():
                (stage / 'ucd' / name).write_bytes(raw)
            with closing(sqlite3.connect(stage / 'geometry.db')) as db:
                db.executescript('PRAGMA foreign_keys=ON;' + SQL)
                result = _check_rows(source, manifest, blobs, native, db, write=True)
                db.commit()
            (stage / 'manifest.json').write_bytes(canonical(result) + b'\n')
        with _verified(stage, native) as (_, _, _, verified):
            stage.rename(output)
            return verified
    finally:
        if stage.exists():
            shutil.rmtree(stage)


def verify(output, native_root):
    with _verified(output, unicode._native(native_root)) as (_, _, _, report):
        return report


def _word(source, db, native, identifier):
    text, receipt = db.execute('SELECT text,receipt FROM words WHERE id=?', (identifier,)).fetchone()
    rows = source.execute('SELECT c.scalar FROM word_characters w JOIN characters c ON c.id=w.character_id '
                          'WHERE w.word_id=? ORDER BY w.ordinal', (identifier,))
    frame = native.unicode_gonol.build_unicode_scalar_frame(''.join(c for c, in rows))
    if frame.recover() != text or frame.receipt != receipt:
        raise ValueError('word differs from its verified interior')
    return frame


def _place(parts, bearings, relation, provenance, native):
    required = sum(kind != 'character' for kind, _ in parts)
    turns = () if bearings is None else tuple(bearings)
    if len(turns) != required:
        raise ValueError(f'{required} explicit closed-object bearings required')
    if not parts:
        raise ValueError('cannot close an empty source')
    supplied = iter(turns)
    children = tuple(obj for _, obj in parts)
    actual = tuple(obj.turn if kind == 'character' else next(supplied) for kind, obj in parts)
    return native.unicode_recursive.close_unicode(children, bearings=actual, relation=relation, source=provenance)


def _result(obj, native, **context):
    return {'profile': PROFILE, 'admission': ADMISSION_RECEIPT, 'recovered': obj.recover(),
            'construction': native.unicode_recursive.export_unicode_graph(obj), **context}


def query(output, text, native_root, bearings=None):
    native = unicode._native(native_root)
    with _verified(output, native) as (source, manifest, db, _):
        parts = []
        words = {}
        for part in segment(text, manifest['metadata']['profile']['abbreviations']):
            if part.kind == 'word':
                if part.text not in words:
                    stored = db.execute('SELECT id FROM words WHERE text=?', (part.text,)).fetchone()
                    if stored is None:
                        raise ValueError(f'word outside pinned corpus: {part.text!r}')
                    words[part.text] = _word(source, db, native, stored[0])
                obj = words[part.text]
            else:
                obj = native.unicode_gonol.unicode_glyph_gonol(part.text)
                if not db.execute('SELECT 1 FROM glyphs WHERE cp=?', (obj.scalar,)).fetchone():
                    raise ValueError('query scalar outside pinned repertoire')
            parts.append((part.kind, obj))
        obj = _place(parts, bearings, 'ordered-text', f'{ADMISSION_RECEIPT}:query:{digest(text)}', native)
        if obj.recover() != text:
            raise ValueError('query source recovery mismatch')
        return _result(obj, native)


def _record(source, db, identifier, native, bearings):
    row = source.execute('SELECT kind,text,owner_record_id,origin_word_id,ordinal,previous_definition_id,'
                         'provenance FROM records WHERE id=?', (identifier,)).fetchone()
    if row is None:
        raise ValueError('unknown source record')
    kind, text, owner, origin, order, previous, provenance = row
    parts, words, components = [], {}, []
    for index, part, wid, symbol, start, end, role in source.execute(
            'SELECT p.ordinal,p.kind,p.word_id,c.scalar,p.start_offset,p.end_offset,p.function FROM components p '
            'LEFT JOIN characters c ON c.id=p.character_id WHERE p.record_id=? ORDER BY p.ordinal', (identifier,)):
        if part == 'word':
            if wid not in words:
                words[wid] = _word(source, db, native, wid)
            child = words[wid]
        else:
            child = native.unicode_gonol.unicode_glyph_gonol(symbol)
        parts.append((part, child))
        components.append({'ordinal': index, 'word_id': wid, 'scalar': symbol, 'start': start, 'end': end,
                           'function': json.loads(role), 'receipt': child.receipt})
    obj = _place(parts, bearings, f'ordered-{kind}', f'{ADMISSION_RECEIPT}:record:{identifier}', native)
    if obj.recover() != text:
        raise ValueError('record differs from verified source')
    return _result(obj, native, source_id=identifier, owner_record_id=owner, origin_word_id=origin,
                   ordinal=order, previous_definition_id=previous, provenance=json.loads(provenance),
                   attachment_reference='SPACE', components=components)


def record(output, identifier, native_root, bearings=None):
    native = unicode._native(native_root)
    with _verified(output, native) as (source, _, db, _):
        return _record(source, db, identifier, native, bearings)


def _definition(source, db, char, ordinal, native, bearings):
    row = db.execute('SELECT entry,relation,source_id,word_id FROM definitions WHERE cp=? AND ordinal=?',
                     (ord(inputs.scalar(char)), ordinal)).fetchone()
    if row is None:
        raise ValueError('unknown inherited definition')
    entry, relation, source_id, wid = row
    glyph = native.unicode_gonol.unicode_glyph_gonol(char)
    owner = native.unicode_recursive.close_unicode((glyph,), relation='character', source=f'{ADMISSION_RECEIPT}:char:{char}')
    parts = [('owner', owner)]
    if wid is not None:
        parts.append(('word', _word(source, db, native, wid)))
    obj = _place(parts, bearings, relation, f'{ADMISSION_RECEIPT}:{source_id}', native)
    return _result(obj, native, entry=json.loads(entry), source_id=source_id, owner=char,
                   number_name_word_id=wid, ordinal=ordinal, attachment_reference='SPACE')


def definition(output, char, ordinal, native_root, bearings=None):
    native = unicode._native(native_root)
    with _verified(output, native) as (source, _, db, _):
        return _definition(source, db, char, ordinal, native, bearings)
