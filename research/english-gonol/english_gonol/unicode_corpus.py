PROFILE = 'uchc.english-unicode-corpus/1'
# Generated by the independently replayed immutable Stack structural candidate.
ADMISSION_MANIFEST_SHA256 = '32c0793e1794f50216393ebc1cf84a8e82604ea66389dc6cdc6ab4a62b6f06ca'
ADMISSION_RECEIPT = '26ab095f73306ff4fbd9f67d1c282c1df79f926bb75cc081c879db8a6989b58a'
